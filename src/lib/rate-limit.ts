// In-memory limiter: good enough for MVP, resets per serverless instance.
// Upgrade path: Upstash Redis (free tier) when you see real abuse.
const hits = new Map<string, number[]>();

export function rateLimit(key: string, max: number, windowMs: number) {
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  recent.push(now);
  hits.set(key, recent);
  return recent.length <= max;
}
